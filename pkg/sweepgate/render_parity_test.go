// markerTimeRe matches the clock at the start of a frame's first line.
var markerTimeRe = regexp.MustCompile(`^\d{2}:\d{2}`)

// provenanceRe is the golden's first-line provenance marker.
var provenanceRe = regexp.MustCompile(`^# generated by sweep-gate\.py@([0-9a-f]{8,})$`)

// generateBase mirrors generate.sh's `${TMPDIR:-/tmp}/sweepgate-generate`.
func generateBase() string {
	base := os.Getenv("TMPDIR")
	if base == "" {
		base = "/tmp"
	}
	return filepath.Join(base, "sweepgate-generate")
}

// parityRenderConfig reproduces the configuration generate.sh used for --render.
//
// The StateDir path is part of the stderr contract: the `park:` line names the
// cadence file it looked for, so it must be the same path the golden captured.
func parityRenderConfig(subject, vault string) Config {
	return Config{
		Vault:            vault,
		Subject:          subject,
		StateDir:         filepath.Join(generateBase(), "render-state"),
		SettledDir:       filepath.Join(generateBase(), "settled"),
		FeedDir:          filepath.Join("..", "..", "testdata", "sweepgate", "inputs", "feed"),
		HoldsPath:        filepath.Join("..", "..", "testdata", "sweepgate", "inputs", "session-holds.json"),
		PredispatchDir:   filepath.Join("..", "..", "testdata", "sweepgate", "inputs", "manager-predispatch"),
		WorkerManagerDir: filepath.Join(generateBase(), "worker-manager"),
		RegistryDir:      ginkgo.GinkgoT().TempDir(),
		HeartbeatDir:     ginkgo.GinkgoT().TempDir(),
		ToolMarkerDir:    ginkgo.GinkgoT().TempDir(),
		TranscriptDir:    ginkgo.GinkgoT().TempDir(),
		StoreURL:         "http://127.0.0.1:1",
		Now:              fixedClock(),
		Interval:         DefaultInterval,
		ReadTimeout:      DefaultReadTimeout,
	}
}

// normalizeFrameClock replaces the marker's HH:MM with HH:MM.
//
// The reference calls datetime.now() and the port uses the injected clock, so the
// minute legitimately differs. Nothing else may be normalised.
func normalizeFrameClock(text string) string {
	idx := strings.IndexByte(text, '\n')
	if idx < 0 {
		return markerTimeRe.ReplaceAllString(text, "HH:MM")
	}
	return markerTimeRe.ReplaceAllString(text[:idx], "HH:MM") + text[idx:]
}

// normalizeFixtureRoot replaces the fixture's temp root with a fixed token.
//
// The goldens are generated inside the container, where `${TMPDIR:-/tmp}` is
// `/tmp`; a host run has `TMPDIR=/var/folders/…`, so the `park:` line's cadence
// path differs by host and the stderr comparison can never pass as captured.
// That path is an environment artifact, not part of the contract — the marker
// clock is normalised for exactly the same reason. Applied to stderr only: the
// frame itself must stay byte-exact.
func normalizeFixtureRoot(text string) string {
	text = strings.ReplaceAll(text, generateBase(), "<FIXTURE>")
	return strings.ReplaceAll(text, "/tmp/sweepgate-generate", "<FIXTURE>")
}

// subjectFromCase turns `parity-topic` into `Parity Topic`.
func subjectFromCase(name string) string {
	words := strings.Split(name, "-")
	for i, word := range words {
		if word == "" {
			continue
		}
		words[i] = strings.ToUpper(word[:1]) + word[1:]
	}
	return strings.Join(words, " ")
}

var _ = ginkgo.Describe("renders the parity fixture", func() {
	ctx := context.Background()

	ginkgo.It("matches the golden stdout and stderr byte for byte", func() {
		goldens, err := filepath.Glob(filepath.Join(
			"..", "..", "testdata", "sweepgate", "*.render.golden.txt"))
		gomega.Expect(err).NotTo(gomega.HaveOccurred())
		gomega.Expect(goldens).NotTo(gomega.BeEmpty())

		for _, goldenPath := range goldens {
			caseName := strings.TrimSuffix(filepath.Base(goldenPath), ".render.golden.txt")
			runGoldenCase(ctx, caseName, goldenPath)
		}
	})

	ginkgo.It("matches a hand-derived frame that is not golden-backed", func() {
		cfg := parityRenderConfig("Second Topic", filepath.Join(
			"..", "..", "testdata", "sweepgate", "vault-second"))
		prepared, err := Prepare(ctx, cfg)
		gomega.Expect(err).NotTo(gomega.HaveOccurred())

		frame, err := Frame(ctx, cfg, prepared, false)
		gomega.Expect(err).NotTo(gomega.HaveOccurred())
		gomega.Expect(frame).NotTo(gomega.ContainSubstring("\x1b]8;"))
		gomega.Expect(frame).To(gomega.Equal(secondFixtureFrame))

		ginkgo.GinkgoWriter.Printf("case=%s golden=false identical=%t",
			"second-topic", frame == secondFixtureFrame)
	})
})

// runGoldenCase renders one fixture and compares stdout and stderr separately.
func runGoldenCase(ctx context.Context, caseName, goldenPath string) {
	golden, err := os.ReadFile(goldenPath)
	gomega.Expect(err).NotTo(gomega.HaveOccurred())
	stderrGolden, err := os.ReadFile(strings.TrimSuffix(goldenPath, ".render.golden.txt") +
		".render.stderr.golden.txt")
	gomega.Expect(err).NotTo(gomega.HaveOccurred())

	// The provenance line proves the golden came from the Python reference.
	parts := strings.SplitN(string(golden), "\n", 2)
	gomega.Expect(parts).To(gomega.HaveLen(2))
	match := provenanceRe.FindStringSubmatch(parts[0])
	gomega.Expect(match).NotTo(gomega.BeNil())
	marker := match[1]
	goldenStdout := parts[1]

	cfg := parityRenderConfig(subjectFromCase(caseName), fixtureVault())
	prepared, err := Prepare(ctx, cfg)
	gomega.Expect(err).NotTo(gomega.HaveOccurred())

	frame, err := Frame(ctx, cfg, prepared, true)
	gomega.Expect(err).NotTo(gomega.HaveOccurred())
	gomega.Expect(frame).NotTo(gomega.ContainSubstring("\x1b]8;"))

	stdout := frame + "\n"
	stderr := normalizeFixtureRoot("park: " + prepared.ParkBasis + "\n")
	goldenStderr := normalizeFixtureRoot(string(stderrGolden))
	identical := normalizeFrameClock(stdout) == normalizeFrameClock(goldenStdout) &&
		stderr == goldenStderr

	gomega.Expect(normalizeFrameClock(stdout)).To(gomega.Equal(normalizeFrameClock(goldenStdout)))
	gomega.Expect(stderr).To(gomega.Equal(goldenStderr))

	ginkgo.GinkgoWriter.Printf(
		"case=%s stdout_bytes=%d stderr_bytes=%d identical=%t marker=%s",
		caseName, len(stdout), len(stderr), identical, marker)
}

