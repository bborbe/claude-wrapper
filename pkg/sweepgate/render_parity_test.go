var _ = ginkgo.Describe("writes the tick on a no-change tick", func() {
	ctx := context.Background()

	ginkgo.It("writes the tick file and keeps stdout silent", func() {
		cfg := parityRenderConfig("Parity Topic", fixtureVault())
		cfg.StateDir = ginkgo.GinkgoT().TempDir()

		prepared, err := Prepare(ctx, cfg)
		gomega.Expect(err).NotTo(gomega.HaveOccurred())
		statePath, err := StatePath(ctx, cfg, cfg.Subject)
		gomega.Expect(err).NotTo(gomega.HaveOccurred())
		gomega.Expect(SaveStored(ctx, statePath, State{
			Topic:     cfg.Subject,
			Digest:    prepared.Digest,
			Members:   len(prepared.Snapshot.Members),
			BusySince: prepared.Busy,
		})).To(gomega.Succeed())

		tickPath, err := TickPath(ctx, cfg, cfg.Subject)
		gomega.Expect(err).NotTo(gomega.HaveOccurred())

		tickWrites := 0
		parkLines := 0
		stdoutBytes := 0
		for i := 0; i < 2; i++ {
			// Remove the file first so each tick proves its own write.
			_ = os.Remove(tickPath)
			var stdout, stderr bytes.Buffer
			code := Tick(ctx, cfg, &stdout, &stderr, nil)
			gomega.Expect(code).To(gomega.Equal(ExitNoChange))

			stdoutBytes += stdout.Len()
			gomega.Expect(stdout.Len()).To(gomega.Equal(0))

			content, readErr := os.ReadFile(tickPath)
			gomega.Expect(readErr).NotTo(gomega.HaveOccurred())
			gomega.Expect(string(content)).To(gomega.ContainSubstring("no change"))
			tickWrites++

			for _, line := range strings.Split(strings.TrimRight(stderr.String(), "\n"), "\n") {
				if strings.HasPrefix(line, "park: ") {
					parkLines++
				}
			}
		}

		gomega.Expect(tickWrites).To(gomega.Equal(2))
		gomega.Expect(parkLines).To(gomega.Equal(2))
		ginkgo.GinkgoWriter.Printf("tick_writes=%d park_lines=%d stdout_bytes=%d",
			tickWrites, parkLines, stdoutBytes)
	})
})
